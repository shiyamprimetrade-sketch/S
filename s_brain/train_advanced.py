"""Training engine with resumable state, gradient accumulation and JSONL metrics.

This module is an opt-in upgrade and does not replace the original s_brain/train.py.
It trains byte IDs with reproducible seeds and a separate validation stream.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import random
import time
from dataclasses import asdict, dataclass
from pathlib import Path

import torch
from torch.nn import functional as F

from .checkpoint import (
    fingerprint_files, load_manifest, resume_training, save_checkpoint,
)
from .model import Config, SBrain


@dataclass
class TrainOptions:
    corpus_dir: Path
    output_dir: Path
    steps: int = 1000
    batch: int = 8
    sequence: int = 128
    accumulate: int = 4
    dim: int = 256
    layers: int = 4
    heads: int = 4
    kv_heads: int = 2
    lr: float = 3e-4
    min_lr: float = 3e-5
    warmup_steps: int = 20
    weight_decay: float = 0.1
    gradient_clip: float = 1.0
    evaluate_every: int = 100
    save_every: int = 200
    evaluation_batches: int = 8
    seed: int = 42
    resume_from: Path | None = None
    trusted_optimizer: bool = False

    def validate(self) -> None:
        positive = ("steps", "batch", "sequence", "accumulate", "dim", "layers",
                    "heads", "kv_heads", "evaluate_every", "save_every",
                    "evaluation_batches")
        for field_name in positive:
            if getattr(self, field_name) < 1:
                raise ValueError(f"{field_name} must be positive")
        if self.dim % self.heads != 0 or self.heads % self.kv_heads != 0:
            raise ValueError("Incompatible attention dimensions")
        if (self.dim//self.heads) % 2:
            raise ValueError("Attention head dimension must be even")
        if self.lr <= 0 or self.min_lr <= 0 or self.min_lr > self.lr:
            raise ValueError("Invalid learning rate")
        if self.warmup_steps < 0:
            raise ValueError("warmup_steps cannot be negative")
        if self.weight_decay < 0 or self.gradient_clip <= 0:
            raise ValueError("Invalid regularization")


class ByteStream:
    """Pure byte input streams; source files are generated by dataset.py."""

    def __init__(self, corpus_dir: Path, sequence: int):
        self.paths = {
            split: corpus_dir / f"{split}.bin"
            for split in ("train", "validation", "test")
        }
        self.data = {}
        for split, path in self.paths.items():
            if not path.exists():
                raise FileNotFoundError(f"Missing {split} byte stream: {path}")
            self.data[split] = torch.tensor(
                list(path.read_bytes()), dtype=torch.long
            )
            if split in ("train", "validation") and len(self.data[split]) < sequence + 2:
                raise ValueError(f"{split} split requires at least sequence+2 bytes")
        self.fingerprint = fingerprint_files(list(self.paths.values()))
        self.sequence = sequence

    def sample(self, split: str, batch_size: int, device: str,
               generator: torch.Generator) -> tuple[torch.Tensor, torch.Tensor]:
        if split not in self.data:
            raise ValueError("Invalid split")
        source = self.data[split]
        if len(source) < self.sequence + 2:
            raise ValueError("Split contains too few tokens")
        start = torch.randint(
            0, len(source)-self.sequence,
            (batch_size,), generator=generator
        )
        offsets = torch.arange(self.sequence)
        tokens = source[start[:,None]+offsets]
        targets = source[start[:,None]+offsets+1]
        return tokens.to(device), targets.to(device)


def set_seed(seed: int) -> None:
    random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def cosine_rate(step: int, total_steps: int, warmup: int,
                peak: float, minimum: float) -> float:
    if total_steps < 1:
        raise ValueError("total_steps must be positive")
    if step < warmup and warmup > 0:
        return peak * (step+1)/warmup
    progress = min(1.0, max(0.0, (step-warmup)/max(1,total_steps-warmup)))
    return minimum + 0.5*(peak-minimum)*(1+math.cos(math.pi*progress))


def parameter_groups(model, weight_decay: float) -> list[dict]:
    decay, no_decay = [], []
    for name, param in model.named_parameters():
        if not param.requires_grad:
            continue
        if param.ndim >= 2:
            decay.append(param)
        else:
            no_decay.append(param)
    return [
        {"params": decay, "weight_decay": weight_decay},
        {"params": no_decay, "weight_decay": 0.0},
    ]


def autocast_context(device: str):
    from contextlib import nullcontext
    if device == "cuda":
        return torch.autocast("cuda", dtype=torch.bfloat16) if torch.cuda.is_bf16_supported() else nullcontext()
    return nullcontext()


@torch.inference_mode()
def validate(model, stream: ByteStream, device: str,
             generator: torch.Generator, batch: int, repeats: int) -> dict:
    model.eval()
    values = []
    for _ in range(repeats):
        x, y = stream.sample("validation", batch, device, generator)
        with autocast_context(device):
            _, loss = model(x,y)
        values.append(float(loss))
    mean = sum(values)/len(values)
    return {
        "loss": mean,
        "perplexity": math.exp(mean) if mean < 700 else float("inf"),
        "batches": repeats,
    }


def append_metrics(path: Path, row: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(row, sort_keys=True, allow_nan=False) + "\n")


def run_training(options: TrainOptions) -> dict:
    options.validate()
    set_seed(options.seed)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    stream = ByteStream(options.corpus_dir, options.sequence)
    config = Config(
        vocab_size=256, dim=options.dim, layers=options.layers,
        heads=options.heads, kv_heads=options.kv_heads, context=options.sequence,
    )
    model = SBrain(config).to(device)
    optimizer = torch.optim.AdamW(
        parameter_groups(model, options.weight_decay),
        lr=options.lr
    )
    generator = torch.Generator(device="cpu").manual_seed(options.seed)
    evaluation_generator = torch.Generator(device="cpu").manual_seed(options.seed+1)
    start_step = 0
    tokens_seen = 0
    if options.resume_from:
        manifest = load_manifest(options.resume_from)
        if manifest.dataset_fingerprint != stream.fingerprint:
            raise ValueError("Refusing to resume against a different dataset")
        manifest = resume_training(
            options.resume_from, model, optimizer,
            trusted_local_optimizer=options.trusted_optimizer,
        )
        start_step = manifest.step
        tokens_seen = manifest.train_tokens
        if start_step >= options.steps:
            raise ValueError("Checkpoint already meets requested training steps")
    options.output_dir.mkdir(parents=True, exist_ok=True)
    metrics_path = options.output_dir / "metrics.jsonl"
    began = time.perf_counter()
    best_loss = float("inf")
    total_parameters = sum(param.numel() for param in model.parameters())
    print(json.dumps({
        "event": "train_start", "device": device,
        "parameters": total_parameters,
        "steps": options.steps, "starting_step": start_step,
        "fingerprint": stream.fingerprint,
    }), flush=True)

    for step in range(start_step+1, options.steps+1):
        model.train()
        optimizer.zero_grad(set_to_none=True)
        rate = cosine_rate(
            step-1, options.steps, options.warmup_steps,
            options.lr, options.min_lr
        )
        for group in optimizer.param_groups:
            group["lr"] = rate
        last_loss = 0.0
        for _ in range(options.accumulate):
            inputs, targets = stream.sample(
                "train", options.batch, device, generator
            )
            with autocast_context(device):
                _, loss = model(inputs, targets)
                scaled = loss/options.accumulate
            scaled.backward()
            last_loss += float(loss.detach())/options.accumulate
            tokens_seen += targets.numel()
        grad = torch.nn.utils.clip_grad_norm_(
            model.parameters(), options.gradient_clip
        )
        if not torch.isfinite(grad):
            raise RuntimeError("Non-finite gradient detected; aborting")
        optimizer.step()
        should_eval = (
            step == 1 or step == options.steps
            or step % options.evaluate_every == 0
        )
        result = None
        if should_eval:
            result = validate(
                model, stream, device, evaluation_generator,
                options.batch, options.evaluation_batches,
            )
            row = {
                "step": step,
                "train_loss": last_loss,
                "validation_loss": result["loss"],
                "validation_perplexity": result["perplexity"],
                "learning_rate": rate,
                "grad_norm": float(grad),
                "tokens_seen": tokens_seen,
                "elapsed_seconds": time.perf_counter()-began,
            }
            append_metrics(metrics_path, row)
            print(json.dumps(row), flush=True)
        should_save = (
            step == options.steps or step % options.save_every == 0
            or (result is not None and result["loss"] < best_loss)
        )
        if result is not None:
            best_loss = min(best_loss, result["loss"])
        if should_save:
            folder = options.output_dir / f"step-{step:08d}"
            save_checkpoint(
                folder, model, config,
                step=step,
                train_tokens=tokens_seen,
                train_loss=last_loss,
                validation_loss=None if result is None else result["loss"],
                seed=options.seed,
                dataset_fingerprint=stream.fingerprint,
                optimizer=optimizer,
                extras={"batch":options.batch,"sequence":options.sequence},
            )
    return {
        "steps": options.steps,
        "tokens_seen": tokens_seen,
        "best_validation_loss": best_loss,
        "model_parameters": total_parameters,
        "checkpoint_root": str(options.output_dir),
    }


def parse_args(argv=None) -> TrainOptions:
    parser = argparse.ArgumentParser(description="S-Brain advanced training")
    parser.add_argument("--corpus-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, default=Path("s_brain/checkpoints/advanced"))
    parser.add_argument("--steps", type=int, default=1000)
    parser.add_argument("--batch", type=int, default=8)
    parser.add_argument("--sequence", type=int, default=128)
    parser.add_argument("--accumulate", type=int, default=4)
    parser.add_argument("--dim", type=int, default=256)
    parser.add_argument("--layers", type=int, default=4)
    parser.add_argument("--heads", type=int, default=4)
    parser.add_argument("--kv-heads", type=int, default=2)
    parser.add_argument("--lr", type=float, default=3e-4)
    parser.add_argument("--min-lr", type=float, default=3e-5)
    parser.add_argument("--warmup-steps", type=int, default=20)
    parser.add_argument("--evaluate-every", type=int, default=100)
    parser.add_argument("--save-every", type=int, default=200)
    parser.add_argument("--evaluation-batches", type=int, default=8)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--resume-from", type=Path)
    parser.add_argument("--trusted-optimizer", action="store_true")
    a = parser.parse_args(argv)
    return TrainOptions(
        corpus_dir=a.corpus_dir, output_dir=a.output_dir,
        steps=a.steps, batch=a.batch, sequence=a.sequence,
        accumulate=a.accumulate, dim=a.dim, layers=a.layers,
        heads=a.heads, kv_heads=a.kv_heads, lr=a.lr,
        min_lr=a.min_lr, warmup_steps=a.warmup_steps,
        evaluate_every=a.evaluate_every, save_every=a.save_every,
        evaluation_batches=a.evaluation_batches, seed=a.seed,
        resume_from=a.resume_from, trusted_optimizer=a.trusted_optimizer,
    )


if __name__ == "__main__":
    print(json.dumps(run_training(parse_args()), indent=2))
